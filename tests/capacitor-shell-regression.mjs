import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8');
const exists = relative => fs.existsSync(path.join(root, relative));
const sha256 = relative => crypto.createHash('sha256').update(fs.readFileSync(path.join(root, relative))).digest('hex');

for (const required of [
  'package.json',
  'package-lock.json',
  'capacitor.config.json',
  'native/native-bridge.js',
  'scripts/build-capacitor-web.mjs',
  'ios/App/App.xcodeproj/project.pbxproj',
  'ios/App/CapApp-SPM/Package.swift',
  'ios/App/App/Info.plist',
]) {
  assert.equal(exists(required), true, `${required} is required for the native iOS shell`);
}

const pkg = JSON.parse(read('package.json'));
assert.equal(pkg.private, true);
assert.deepEqual(pkg.dependencies, {
  '@capacitor/core':'8.5.1',
  '@capacitor/geolocation':'8.2.2',
  '@capacitor/ios':'8.5.1',
  '@capacitor/local-notifications':'8.3.1',
});
assert.deepEqual(pkg.devDependencies, {
  '@capacitor/cli':'8.5.1',
  'esbuild':'0.28.2',
});
assert.deepEqual(pkg.overrides, { uuid:'11.1.1' });
assert.equal(pkg.scripts['native:web'], 'node scripts/build-capacitor-web.mjs');
assert.equal(pkg.scripts['native:sync'], 'npm run native:web && cap sync ios');
assert.equal(pkg.scripts['native:doctor'], 'cap doctor');

const config = JSON.parse(read('capacitor.config.json'));
assert.equal(config.appId, 'com.bocametrics.wavelength');
assert.equal(config.appName, 'Wavelength');
assert.equal(config.webDir, 'www');
assert.deepEqual(config.plugins?.LocalNotifications?.presentationOptions, ['banner', 'list', 'sound']);
assert.match(read('sw.js'), /const CACHE_NAME = 'wavelength-mobile-v31';/,
  'the PWA cache advances with the native-shell and product changes');

const bridge = read('native/native-bridge.js');
assert.match(bridge, /from '@capacitor\/core'/);
assert.match(bridge, /from '@capacitor\/geolocation'/);
assert.match(bridge, /from '@capacitor\/local-notifications'/);
assert.match(bridge, /Capacitor\.isNativePlatform\(\)/);
assert.match(bridge, /checkPermissions/);
assert.match(bridge, /requestPermissions/);
assert.match(bridge, /LocalNotifications\.schedule/);
assert.match(bridge, /LocalNotifications\.cancel/);
assert.match(bridge, /localNotificationActionPerformed/);
assert.match(bridge, /window\.WavelengthNative\s*=/);

const build = read('scripts/build-capacitor-web.mjs');
assert.match(build, /index\.html/);
assert.match(build, /manifest\.webmanifest/);
assert.match(build, /sw\.js/);
assert.match(build, /icons/);
assert.match(build, /native-bridge\.js/);
assert.match(build, /esbuild/);
assert.match(build, /<script src="\.\/native-bridge\.js"><\/script>/);

const gitignore = read('.gitignore');
assert.match(gitignore, /^node_modules\/$/m);
assert.match(gitignore, /^www\/$/m);
assert.match(read('ios/.gitignore'), /^App\/App\/public$/m);

const project = read('ios/App/App.xcodeproj/project.pbxproj');
assert.match(project, /PRODUCT_BUNDLE_IDENTIFIER = com\.bocametrics\.wavelength;/);
const packageSwift = read('ios/App/CapApp-SPM/Package.swift');
assert.match(packageSwift, /CapacitorGeolocation/);
assert.match(packageSwift, /CapacitorLocalNotifications/);
const info = read('ios/App/App/Info.plist');
assert.match(info, /<key>NSLocationAlwaysAndWhenInUseUsageDescription<\/key>\s*<string>Wavelength uses your approximate location to tailor weather, air-quality, and light recommendations\.<\/string>/);
assert.match(info, /<key>NSLocationWhenInUseUsageDescription<\/key>\s*<string>Wavelength uses your approximate location to tailor weather, air-quality, and light recommendations\.<\/string>/);

assert.notEqual(
  sha256('ios/App/App/Assets.xcassets/AppIcon.appiconset/AppIcon-512@2x.png'),
  '29e4777e319de3ee5a52c3a8004ec19d0568414004257e36d7c94a077d71c93b',
  'the Capacitor placeholder app icon must be replaced',
);
for (const splash of ['splash-2732x2732.png', 'splash-2732x2732-1.png', 'splash-2732x2732-2.png']) {
  assert.notEqual(
    sha256(`ios/App/App/Assets.xcassets/Splash.imageset/${splash}`),
    '1b5002b74a5500e697298ced06ca2811ac33f2771f236f3c720ff23243890530',
    `${splash} must use Wavelength launch branding`,
  );
}

for (const generated of ['www/index.html', 'www/native-bridge.js', 'www/manifest.webmanifest', 'www/sw.js']) {
  assert.equal(exists(generated), true, `${generated} is generated by native:web`);
}
const nativeIndex = read('www/index.html');
assert.match(nativeIndex, /<script src="\.\/native-bridge\.js"><\/script>/);
assert.equal(read('www/sw.js'), read('sw.js'), 'native web assets use the current PWA service worker bytes');
assert.doesNotMatch(nativeIndex, /Install Wavelength on your iPhone|installCard|setupInstallTip/);
assert.doesNotMatch(read('index.html'), /<script src="\.\/native-bridge\.js"><\/script>/,
  'the browser source stays independent of the bundled native adapter');

console.log('Capacitor iOS shell regression tests passed');
